#!/usr/bin/env python3
"""Optional: check that external URLs in README.md respond.

Not run in CI (it would add flaky network calls). Run locally before pushing:
    python scripts/check_external_links.py
Generated branch URLs (output/...) are skipped because they only exist after the
snake workflow has run. Third-party stats services may rate-limit; treat 429/5xx
as informational. Use --strict to exit 1 on any failure.
"""
import html
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

readme = (Path(__file__).resolve().parent.parent / "README.md").read_text(encoding="utf-8")
urls = sorted({html.unescape(u) for u in re.findall(r'(?:src|srcset|href)="(https?://[^"]+)"', readme)}
              | set(re.findall(r"\]\((https?://[^)\s]+)", readme)))
failed = 0
for url in urls:
    if "/output/" in url:
        print(f"SKIP  {url}  (generated by workflow)")
        continue
    req = urllib.request.Request(url, headers={"User-Agent": "profile-link-check"})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            print(f"OK    {r.status}  {url}")
    except urllib.error.HTTPError as ex:
        failed += 1
        print(f"FAIL  {ex.code}  {url}")
    except Exception as ex:
        failed += 1
        print(f"FAIL  {type(ex).__name__}  {url}")
print(f"\n{failed} failure(s) of {len(urls)} URL(s)")
sys.exit(1 if failed and "--strict" in sys.argv else 0)
